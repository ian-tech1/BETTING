import type { FormMark, RawMatch, Side } from "@/data/weekend";

export type LiveGoal = { minute: number; side: "home" | "away" };

export type LiveInput = RawMatch & {
  /** Shifts the desk clock so matches are not all on the same minute. */
  offsetMin: number;
  goals: LiveGoal[];
  flag?: string;
};

function side(
  name: string,
  short: string,
  pos: number,
  form: FormMark[],
  xgFor: number,
  xgAgainst: number,
): Side {
  return {
    name,
    short,
    pos,
    form,
    xgFor,
    xgAgainst,
    gf: Math.round(xgFor * 10),
    ga: Math.round(xgAgainst * 10),
    played: 10,
    out: [],
  };
}

